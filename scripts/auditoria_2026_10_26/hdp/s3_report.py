import pickle, numpy as np
R = pickle.load(open("s3_rows.pkl", "rb")); a = lambda k: np.array([r[k] for r in R], float)
n = len(R); print("n =", n)
print("Delta(best-fin) media:", (a('best')-a('fin')).mean(), " K mean:", a('K').mean())
print("Delta(media post-burn - fin):", (a('post_mean')-a('fin')).mean(), " sesgo max-vs-media (best - post_mean) media:", (a('best')-a('post_mean')).mean(), "mediana", np.median(a('best')-a('post_mean')))
print("best_iteration dentro del burn-in (<=40):", int((a('best_it')<=40).sum()), "/", n)
print("ll en medias posteriores - best: media", (a('ll_pm')-a('best')).mean(), " min", (a('ll_pm')-a('best')).min())
print("K best mean", a('K').mean(), " K post-burn mean", a('K_post').mean(), " K occ>=2%", a('K_occ2').mean(), " estados con 1 sola visita en best (media)", a('K_singleton').mean())
print("unigram in-sample - fin: media", (a('uni')-a('fin')).mean(), " obras con unigram > fin:", int((a('uni')>a('fin')).sum()))
print("best_hdp - unigram: media", (a('best')-a('uni')).mean(), " por token", ((a('best')-a('uni'))/a('T')).mean())
print("beta: max|cambio| en 1a llamada: media", a('dbeta1').mean(), " max|cambio| en llamadas 2..80: max", a('dbeta_rest').max())
ho = a('ho_n')
for k in ['ho_hdp','ho_hdp_pm','ho_fin','ho_uni']: print(k, "por token test:", (a(k)/ho).mean())
print("held-out HDP(best) > fin en", int((a('ho_hdp')>a('ho_fin')).sum()), "/", n, "; HDP(best) > unigram en", int((a('ho_hdp')>a('ho_uni')).sum()), "/", n)
print("held-out HDP - fin total (suma)/obra media:", (a('ho_hdp')-a('ho_fin')).mean())
